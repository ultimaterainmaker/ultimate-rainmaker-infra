const exact = {};
const prefixes = [];
for (const county of Object.keys(ACCEPTED)) {
  for (const z of String(ACCEPTED[county]).split(/[\s,]+/)) {
    if (!z) continue;
    if (z.endsWith('*')) prefixes.push([z.slice(0, -1), county]);
    else exact[z] = county;
  }
}

function countyFor(zip) {
  if (exact[zip]) return exact[zip];
  const hit = prefixes.find(([p]) => zip.startsWith(p));
  return hit ? hit[1] : '';
}

// Dedicated zip field wins. Otherwise take the LAST 5-digit group in the address,
// so a 5-digit house number ("12345 Main St ... 17003") doesn't get picked. Handles ZIP+4.
function extractZip(zipField, address) {
  const direct = String(zipField || '').replace(/\D/g, '');
  if (direct.length >= 5) return direct.slice(0, 5);
  const matches = String(address || '').match(/\b\d{5}(?:-\d{4})?\b/g);
  return matches ? matches[matches.length - 1].slice(0, 5) : '';
}

